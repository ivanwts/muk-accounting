let lang = "en";
try { lang = localStorage.getItem("lang") || lang; } catch (e) {}
if (!T[lang]) lang = "en";

function applyLang() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = T[lang][el.dataset.i18n];
    if (value !== undefined) el.innerHTML = value;
  });
  document.querySelectorAll(".lang button").forEach((b) => b.classList.toggle("is-active", b.dataset.lang === lang));
  if (CONFIG.hours[lang]) document.getElementById("c-hours").textContent = CONFIG.hours[lang];
}

document.querySelectorAll(".lang button").forEach((b) =>
  b.addEventListener("click", () => {
    lang = b.dataset.lang;
    try { localStorage.setItem("lang", lang); } catch (e) {}
    applyLang();
  })
);

